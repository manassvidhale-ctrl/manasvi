export function getWeekData(week: number): PregnancyWeekData {
  const normalizedWeek = Math.min(Math.max(week, 4), 40);
  const exact = PREGNANCY_WEEKS.find(w => w.week === normalizedWeek);
  if (exact) return exact;

  // Find nearest
  const sorted = [...PREGNANCY_WEEKS].sort((a, b) => Math.abs(a.week - normalizedWeek) - Math.abs(b.week - normalizedWeek));
  const closest = sorted[0];

  // Return synthesized closest week info
  const trimester = normalizedWeek <= 13 ? 1 : normalizedWeek <= 27 ? 2 : 3;
  return {
    ...closest,
    week: normalizedWeek,
    trimester
  };
}
